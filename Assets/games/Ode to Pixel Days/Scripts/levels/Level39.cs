			}

			if (patternMatcher.cevapver)
			{
				patternMatcher.cevapver = false;
				lever2sUsable();
			}

			if ((!leverHapis.isOpen || boss.x < 1000) && lever2light1.usable && !bossIsDead)
			{
				lever2sNotUsable();
			}

			if (patternMatcher.canavarGonder)
			{
				patternMatcher.canavarGonder = false;
				for (i = 1; i < 3; ++i)
				{
					if (FlxG.random() < 0.2)
					{
						monsters.add(new MonsterGoomba(800 + i * 60, -64, scale));
					}
					else
					{
						monsters.add(new MonsterGel(800 + i * 60, -64, scale));
					}
				}
			}

			if (!abstractLever.isOpen && player.x >= 776)
			{
				abstractLever.isOpen = true;
				abstractLever2.isOpen = true;
				if (FlxG.music != null)
				{
					FlxG.music.volume = 0.5;
				}
			}

			if (boss.x > 944 && boss.x < 1008 && boss.y > 100 && leverHapis.isOpen && blockHapis.y > 120)
			{
				if (boss.velocity.x < 0)
				{
					boss.velocity.x = -800;
				}
				else
				{
					boss.velocity.x = 800;
				}

				if (boss.x >= 944 && boss.x <= 1008)
				{
					boss.x = 1024;
				}
			}

			if (!bossIsTrapped && (boss.x >= 1008 && boss.y > 24 && leverHapis.isOpen))
			{
				patternMatcher.start();
			}

			bossIsTrapped = boss.x >= 1008 && boss.y > 24 && leverHapis.isOpen;
			if (!leverHapisIsOpen && leverHapis.isOpen)
			{
				for (int k = 0; k < monsters.members.Count; k++)
				{
					_m = monsters.members[k] as Monster;
					if (_m == null)
					{
						continue;
					}

					if (!_m.isDead && _m.y > 88 && _m.x >= 960 && _m.x <= 1008)
					{
						if (!(_m is MonsterHans))
						{
							_m.x = 950;
						}
					}
				}
			}

			leverHapisIsOpen = leverHapis.isOpen;
			if (player.x < 776)
			{
				camera.x = player.x;
			}
			else if (player.x <= 1068)
			{
				if (camera.x < 907)
				{
					camera.velocity.x = 160;
