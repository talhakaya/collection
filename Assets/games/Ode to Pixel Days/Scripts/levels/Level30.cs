		public override void update()
		{
			base.update();
			if (count == 0 && !startedToRainBlocks && player.x > 63)
			{
				startedToRainBlocks = true;
			}

			if (startedToRainBlocks)
			{
				++count;
				if (count == 1)
				{
					blocks.add(new BlockFalling(116, -96, scale, false, true));
				}
				else if (count == 15)
				{
					blocks.add(new BlockFalling(148, -96, scale, false, true));
				}
				else if (count > 15)
				{
					startedToRainBlocks = false;
				}
			}

			if (player.y > 240)
			{
				instantDeath();
			}

			if (player.fading)
			{
				cheerleader.gone = true;
			}

			FlxG.collide(level, cheerleader);
			FlxG.overlap<Cheerleader, Machine>(cheerleader, interacts, cheerleaderOverlappedWithMachine);
			FlxG.collide<Hans, FlxSprite>(player, blocks, blockCollision);
			FlxG.collide<FlxTilemap, BlockFalling>(level, blocks, blockParticle);
			FlxG.collide(blocks);
		}

