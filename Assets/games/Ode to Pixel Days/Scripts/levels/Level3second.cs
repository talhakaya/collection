		public override void update()
		{
			base.update();
			if (timerForMonsters.complete)
			{
				makeMonsters();
			}

			if (lever.isOpen && tuto.alpha > 0)
			{
				tuto.alpha -= 0.02;
			}
		}

		protected override void overlapped(FlxSprite Sprite1, FlxSprite Sprite2)
		{
			base.overlapped(Sprite1, Sprite2);
			if (Sprite1 is Hans && Sprite2 is Lever && player.interact)
			{
				lever.used = true;
			}
		}

		private void makeMonsters()
		{
			if (!lever.isOpen)
			{
				if (count > 10)
				{
					count = 0;
					isLeft = !isLeft;
				}
				else
				{
					++count;
				}

				monsters.add(new MonsterGelBlue(192 + FlxG.random() * 32, -8, scale));
				if (isLeft)
				{
					monsters.add(new MonsterGelBlue(144 + FlxG.random() * 32, -8, scale));
				}
				else
				{
					monsters.add(new MonsterGelBlue(240 + FlxG.random() * 32, -8, scale));
				}

				timerForMonsters.start(6);
			}
		}

		public override void interactWithDoor(FlxSprite Sprite2)
		{
			if (lever.isOpen)
			{
				base.interactWithDoor(Sprite2);
			}
		}

		public override void nextLevel()
		{
			FlxG.switchState(new Level4());
		}

		public override void addBgDetail()
		{
			bgDetails[0][1] = "windowBig00";
			bgDetails[1][1] = "windowBig20";
			bgDetails[0][2] = "windowBig02";
			bgDetails[1][2] = "windowBig22";
		}

		private void selaleSfx(FlxTimer a)
		{
			double volume = double.NaN;
			if (!lever.isOpen)
			{
				volume = 1 - Math.Abs(204 - player.x) / 240;
				timerForSfx.start(1, 1, selaleSfx);
				FlxG.play(Sfx, volume);
			}
		}
